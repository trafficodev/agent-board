_validation_task: asyncio.Task | None = None


@app.on_event("startup")
async def _start_validation_worker():
    """Deterministic card checks run in the background for as long as the server
    does. Off by env var for anyone who wants a quiet board."""
    global _validation_task
    db.initialize_storage()
    try:
        board_consolidation.recover_pending_consolidations()
    except Exception as exc:
        sys.stderr.write(
            f"Board consolidation recovery failed: {type(exc).__name__}\n"
        )
    if validation_worker.is_enabled():
        _validation_task = asyncio.create_task(validation_worker.run_forever())


@app.on_event("shutdown")
async def _stop_validation_worker():
    global _validation_task
    if _validation_task:
        _validation_task.cancel()
        with suppress(asyncio.CancelledError):
            await _validation_task
        _validation_task = None


_CARD_MUTATION_RE = re.compile(
    r"^/api/boards/[0-9a-f]{12}/cards(?:$|/bulk$|/[0-9a-f]{12}"
    r"(?:$|/move$|/sessions$|/notes(?:$|/[0-9a-f]{12}/answer$)|/revert$"
    r"|/changes/[0-9a-f]{64}/vote$))"
)


def _requires_change_context(method: str, path: str) -> bool:
    return method in {"POST", "PATCH", "DELETE"} and bool(
        _CARD_MUTATION_RE.fullmatch(path)
    )


@app.middleware("http")
async def _guard_consolidations(request, call_next):
    is_consolidation = request.url.path == "/api/projects/consolidate-board"
    lock_file = open(board_consolidation.api_lock_path(), "w")
    operation = fcntl.LOCK_EX if is_consolidation else fcntl.LOCK_SH
    await asyncio.to_thread(fcntl.flock, lock_file, operation)
    try:
        if board_consolidation.has_pending_consolidation() and not is_consolidation:
            return JSONResponse(
                status_code=503,
                content={"detail": "Board consolidation recovery is pending"},
            )
        return await call_next(request)
    finally:
        await asyncio.to_thread(fcntl.flock, lock_file, fcntl.LOCK_UN)
        lock_file.close()


@app.middleware("http")
async def _bind_change_context(request, call_next):
    context = None
    if _requires_change_context(request.method, request.url.path):
        try:
            context = ChangeContext.from_headers(request.headers)
        except ValueError as exc:
            return JSONResponse(status_code=400, content={"detail": str(exc)})
    token = cs.request_change_context.set(context)
    try:
        return await call_next(request)
    finally:
        cs.request_change_context.reset(token)


def _validate_id(value: str, name: str = "id") -> str:
    if not _ID_RE.match(value):
        raise HTTPException(400, f"Invalid {name}")
    return value


