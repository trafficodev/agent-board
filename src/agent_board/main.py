@app.get("/api/boards/{board_id}/cards")
def api_list_cards(
    board_id: str,
    priority: str | None = None,
    label: str | None = None,
    column_id: str | None = None,
    parent_id: str | None = None,
    sort: str = "board",
    limit: int = Query(card_projection.DEFAULT_PAGE_LIMIT, ge=1, le=card_projection.MAX_PAGE_LIMIT),
    cursor: str | None = None,
    include: list[str] | None = Query(None, description=card_projection.INCLUDE_FIELDS_DESCRIPTION),
    exclude: list[str] | None = Query(None, description=card_projection.EXCLUDE_FIELDS_DESCRIPTION),
):
    """List cards. The default projection contains every card and derived field."""
    _board_or_404(board_id)
    cards = [card.model_dump(mode="json") for card in cs.list_cards(board_id, priority=priority, label=label, column_id=column_id, parent_id=parent_id)]
    coverage = card_projection.coverage_extras(
        cards,
        [edge.model_dump(mode="json") for edge in es.list_edges(board_id)],
    )
    ordered = search_logic.sort_cards(cards, sort, tie_breaker=True)
    try:
        selected_fields = card_projection.resolve_card_fields(
            "list_cards", include=include, exclude=exclude
        )
        return card_projection.page_cards(
            ordered,
            board_id=board_id,
            endpoint="list_cards",
            request={
                "priority": priority,
                "label": label,
                "column_id": column_id,
                "parent_id": parent_id,
                "sort": sort,
            },
            limit=limit,
            cursor=cursor,
            sort_key=lambda card: search_logic.card_sort_key(card, sort),
            item_extras=coverage,
            selected_fields=selected_fields,
        )
    except card_projection.InvalidCursor as exc:
        raise HTTPException(400, str(exc)) from exc
    except card_projection.StaleCursor as exc:
        raise HTTPException(400, str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc


@app.get("/api/boards/{board_id}/cards/search")
def api_search_cards(
    board_id: str,
    query: str = "",
    priority: str | None = None,
    label: str | None = None,
    sort: str = "board",
    limit: int = Query(card_projection.DEFAULT_PAGE_LIMIT, ge=1, le=card_projection.MAX_PAGE_LIMIT),
    cursor: str | None = None,
    include: list[str] | None = Query(None, description=card_projection.INCLUDE_FIELDS_DESCRIPTION),
    exclude: list[str] | None = Query(None, description=card_projection.EXCLUDE_FIELDS_DESCRIPTION),
):
    """Search cards with every card field, derived field, and relation_roles by default."""
    board = _board_or_404(board_id)
    cards = [card.model_dump(mode="json") for card in cs.list_cards(board_id)]
    columns = [column.model_dump(mode="json") for column in board.columns]
    edges = [edge.model_dump(mode="json") for edge in es.list_edges(board_id)]
    coverage = card_projection.coverage_extras(cards, edges)
    try:
        ordered, relation_roles = search_logic.search_cards_with_roles(
            cards, columns, query=query, priority=priority, label=label, edges=edges, sort=sort
        )
        ordered = search_logic.sort_cards(ordered, sort, tie_breaker=True)
        selected_fields = card_projection.resolve_card_fields(
            "search_cards", include=include, exclude=exclude
        )
        return card_projection.page_cards(
            ordered,
            board_id=board_id,
            endpoint="search_cards",
            request={
                "query": query,
                "priority": priority,
                "label": label,
                "sort": sort,
            },
            limit=limit,
            cursor=cursor,
            sort_key=lambda card: search_logic.card_sort_key(card, sort),
            relation_roles=relation_roles,
            item_extras=coverage,
            selected_fields=selected_fields,
        )
    except card_projection.InvalidCursor as exc:
        raise HTTPException(400, str(exc)) from exc
    except card_projection.StaleCursor as exc:
        raise HTTPException(400, str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc


@app.get("/api/boards/{board_id}/cards/relevant-candidates")
def api_relevant_candidates(
    board_id: str,
    query: str = "",
    priority: str | None = None,
    label: str | None = None,
    max_candidates: int = Query(search_logic._SHORTLIST_CAP, ge=1, le=50),
    limit: int = Query(card_projection.DEFAULT_PAGE_LIMIT, ge=1, le=card_projection.MAX_PAGE_LIMIT),
    cursor: str | None = None,
    include: list[str] | None = Query(None, description=card_projection.INCLUDE_FIELDS_DESCRIPTION),
    exclude: list[str] | None = Query(None, description=card_projection.EXCLUDE_FIELDS_DESCRIPTION),
):
    """Keyword-relevance shortlist only -- a building block for semantic/AI
    ranking, not itself a semantic ranker (agent-board has no AI provider).
    Callers who want AI ranking send this candidate list to a model themselves.
    The default projection includes every card field, derived field,
    relevance_score, and column."""
    board = _board_or_404(board_id)
    cards = [card.model_dump(mode="json") for card in cs.list_cards(board_id)]
    columns = [column.model_dump(mode="json") for column in board.columns]
    edges = [edge.model_dump(mode="json") for edge in es.list_edges(board_id)]
    coverage = card_projection.coverage_extras(cards, edges)
    try:
        ranked, scores, column_names, error = search_logic.ranked_relevant_cards(
            cards,
            columns,
            query=query,
            priority=priority,
            label=label,
            edges=edges,
            max_candidates=max_candidates,
        )
        extras = {
            card["id"]: {
                "relevance_score": scores[card["id"]],
                "column": column_names.get(card.get("column_id"), card.get("column_id", "")),
                **coverage.get(card["id"], {}),
            }
            for card in ranked
        }
        selected_fields = card_projection.resolve_card_fields(
            "relevant_candidates", include=include, exclude=exclude
        )
        return card_projection.page_cards(
            ranked,
            board_id=board_id,
            endpoint="relevant_candidates",
            request={
                "query": query,
                "priority": priority,
                "label": label,
                "max_candidates": max_candidates,
            },
            limit=limit,
            cursor=cursor,
            sort_key=lambda card: (
                -scores[card["id"]],
                *search_logic.card_sort_key(card, "board"),
            ),
            item_extras=extras,
            envelope_extras={"error": error},
            selected_fields=selected_fields,
        )
    except card_projection.InvalidCursor as exc:
        raise HTTPException(400, str(exc)) from exc
    except card_projection.StaleCursor as exc:
        raise HTTPException(400, str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc


